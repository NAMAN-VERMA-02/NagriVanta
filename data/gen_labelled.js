// Generates civic_labelled_india.json: SYNTHETIC, hand-templated demo reports with human labels.
// Used for seeding the demo and for evaluating the AI/rule classifier. Not real citizen data.
// Run: node data/gen_labelled.js
const fs = require('fs');
const path = require('path');

const wards = [
  { ward: 'Indirapuram', lat: 28.6460, lng: 77.3695 },
  { ward: 'Vaishali', lat: 28.6448, lng: 77.3388 },
  { ward: 'Raj Nagar Extension', lat: 28.6956, lng: 77.4180 },
  { ward: 'Kavi Nagar', lat: 28.6729, lng: 77.4497 },
  { ward: 'Sector 62 Noida', lat: 28.6270, lng: 77.3725 },
  { ward: 'Vasundhara', lat: 28.6604, lng: 77.3647 },
];

// [category, priority, title, description]
const templates = [
  ['road', 'high', 'Deep pothole on main road', 'Large deep pothole near the school gate, two-wheelers are skidding and one person fell yesterday.'],
  ['road', 'medium', 'Road surface broken', 'Road surface is broken for about 50 metres after the pipeline work, cars slow down a lot.'],
  ['road', 'low', 'Small crack on service lane', 'Small cracks forming on the service lane, not urgent but getting wider.'],
  ['road', 'high', 'सड़क पर बड़ा गड्ढा', 'मुख्य सड़क पर बहुत बड़ा गड्ढा है, बाइक वाले गिर रहे हैं, कृपया जल्दी ठीक करें।'],
  ['road', 'medium', 'Speed breaker damaged', 'Speed breaker is broken and iron rods are sticking out near the market.'],
  ['garbage', 'medium', 'Garbage not collected', 'Garbage has not been collected for 4 days, bins overflowing and bad smell in the lane.'],
  ['garbage', 'high', 'Garbage dump near hospital', 'Huge garbage dump next to the hospital entrance, stray dogs and flies everywhere, health risk.'],
  ['garbage', 'low', 'Litter in park', 'Plastic wrappers and litter lying around in the park after the weekend.'],
  ['garbage', 'medium', 'kooda nahi utha', 'Gali me 3 din se kooda pada hai, safai karmachari nahi aaye.'],
  ['water', 'high', 'Major water pipe burst', 'Main water pipeline burst, water flooding the road and supply cut for the whole block.'],
  ['water', 'medium', 'Water leakage from pipe', 'Continuous leakage from the water pipe near the tank, lots of clean water wasted.'],
  ['water', 'medium', 'Dirty water supply', 'Tap water is coming muddy and smelly since two days.'],
  ['water', 'low', 'Low water pressure', 'Water pressure is very low in the mornings.'],
  ['streetlight', 'high', 'Street lights off on dark stretch', 'All street lights are off on this stretch for a week, women feel unsafe walking at night.'],
  ['streetlight', 'medium', 'Streetlight not working', 'The streetlight pole number 14 is not working.'],
  ['streetlight', 'low', 'Light flickering', 'Street lamp keeps flickering at night.'],
  ['streetlight', 'high', 'Exposed wires on light pole', 'Electric wires hanging out of the street light pole, children play nearby, danger of shock.'],
  ['drainage', 'high', 'Waterlogging after rain', 'Severe waterlogging after rain, road blocked and water entering houses.'],
  ['drainage', 'medium', 'Drain blocked', 'Open drain is choked with plastic and overflowing onto the footpath.'],
  ['drainage', 'medium', 'Sewer overflow', 'Sewer manhole overflowing with dirty water, very bad smell.'],
  ['drainage', 'high', 'Open manhole', 'Manhole cover missing on the main road, someone can fall in at night.'],
  ['drainage', 'low', 'nali saaf karo', 'Nali me thoda kachra jama hai, saaf karwa dijiye.'],
  ['other', 'low', 'Stray cattle on road', 'Stray cows sitting in the middle of the road every evening.'],
  ['other', 'low', 'Park bench broken', 'One of the benches in the community park is broken.'],
];

let seed = 42;
const rand = () => ((seed = (seed * 16807) % 2147483647) / 2147483647);

const out = [];
for (let i = 0; i < 120; i++) {
  const [category, priority, title, description] = templates[i % templates.length];
  const w = wards[Math.floor(rand() * wards.length)];
  out.push({
    id: `SYN-${String(i + 1).padStart(3, '0')}`,
    title,
    description,
    label: { category, priority },
    ward: w.ward,
    location: { lat: +(w.lat + (rand() - 0.5) * 0.02).toFixed(5), lng: +(w.lng + (rand() - 0.5) * 0.02).toFixed(5) },
    daysAgo: Math.floor(rand() * 60),
  });
}

fs.writeFileSync(path.join(__dirname, 'civic_labelled_india.json'), JSON.stringify({
  note: 'SYNTHETIC demo data generated by gen_labelled.js. Labels are human-assigned per template. Not real complaints.',
  categories: ['road', 'garbage', 'water', 'streetlight', 'drainage', 'other'],
  items: out,
}, null, 2));
console.log(`wrote ${out.length} items`);
